<?php

namespace App\Models;

use App\Enums\AccessType;
use App\Enums\ContentFormat;
use App\Enums\ContentStatus;
use Database\Factories\ContentSourceFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Storage;

/**
 * A way to read one story: a file on the private reader disk, or a link out. Nothing is streamed unless an admin verified the source (or it is the
 * owner's own upload); that rule lives in App\Reader\ContentAccessGate. `storage_path` is generated by the server and `original_name` is only ever
 * shown, never used in a path.
 *
 * @property int $id
 * @property int $media_id
 * @property AccessType $access_type
 * @property ContentFormat $format
 * @property string|null $storage_path
 * @property string|null $url
 * @property string $license
 * @property string|null $rights_holder
 * @property int|null $owner_user_id
 * @property int|null $verified_by
 * @property Carbon|null $verified_at
 * @property ContentStatus $status
 * @property string|null $failure_reason
 * @property int|null $byte_size
 * @property string|null $mime_type
 * @property string|null $checksum
 * @property string|null $original_name
 * @property string|null $external_key
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
#[Fillable(['media_id', 'access_type', 'format', 'storage_path', 'url', 'license', 'rights_holder', 'owner_user_id', 'verified_by', 'verified_at', 'status', 'failure_reason', 'byte_size', 'mime_type', 'checksum', 'original_name', 'external_key'])]
class ContentSource extends Model
{
    /** @use HasFactory<ContentSourceFactory> */
    use HasFactory;

    /**
     * The model's default attribute values.
     *
     * @var array<string, mixed>
     */
    protected $attributes = [
        'status' => 'pending',
    ];

    protected static function booted(): void
    {
        // A deleted source takes its file with it, so no orphan is left on the private disk.
        static::deleting(function (ContentSource $source): void {
            if ($source->storage_path !== null) {
                Storage::disk(self::disk())->delete($source->storage_path);
            }
        });
    }

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'access_type' => AccessType::class,
            'format' => ContentFormat::class,
            'status' => ContentStatus::class,
            'byte_size' => 'integer',
            'verified_at' => 'datetime',
        ];
    }

    /**
     * The private disk the reader files live on.
     */
    public static function disk(): string
    {
        return (string) config('bookflix.reader.disk');
    }

    /**
     * Whether the source has been verified: by an admin, or for an owner's own upload by the upload itself (no admin, so `verified_by` is null).
     */
    public function isVerified(): bool
    {
        if ($this->verified_at === null) {
            return false;
        }

        return $this->access_type === AccessType::UserOwned || $this->verified_by !== null;
    }

    /**
     * @return BelongsTo<Media, $this>
     */
    public function media(): BelongsTo
    {
        return $this->belongsTo(Media::class);
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function owner(): BelongsTo
    {
        return $this->belongsTo(User::class, 'owner_user_id');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function verifier(): BelongsTo
    {
        return $this->belongsTo(User::class, 'verified_by');
    }
}
